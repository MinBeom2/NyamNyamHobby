-- 냠냠취미 DB 스키마 v0.3 (PostgreSQL 16+, MySQL 8.0 원본에서 변환)
-- v0.4 메모(기능 요구사항 CSV 10/21 반영): 스키마는 바꾸지 않음. P2(MVP 제외) 기능용 테이블·컬럼
--       (guest_key, short_saves, interest_selections, notifications, feedbacks, PAUSED 등)은 고도화 대비로 남김
-- 규칙: 테이블·컬럼 snake_case / PK BIGINT IDENTITY / 시간 TIMESTAMP(6) UTC 저장 / TINYINT→SMALLINT(엔티티는 Short) / JSON→JSONB
--       enum은 VARCHAR + JPA @Enumerated(EnumType.STRING) / 삭제는 status 또는 deleted_at (soft delete)
-- 변환 메모: posts의 FULLTEXT(ngram) 인덱스는 PostgreSQL에 같은 기능이 없어 제외함.
--       게시글 검색 방식(pg_trgm, tsvector 등)을 정한 뒤 V2 마이그레이션으로 추가

-- ───────── 회원 ─────────
CREATE TABLE users (
  id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email             VARCHAR(100) NOT NULL,
  password_hash     VARCHAR(100) NULL,
  nickname          VARCHAR(12)  NOT NULL,
  profile_image_url VARCHAR(500) NULL,
  role              VARCHAR(10)  NOT NULL DEFAULT 'USER',
  status            VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
  email_verified_at TIMESTAMP(6)  NULL,
  interest_reset_at TIMESTAMP(6)  NULL,
  login_fail_count  INT          NOT NULL DEFAULT 0,
  locked_until      TIMESTAMP(6)  NULL,
  created_at        TIMESTAMP(6)  NOT NULL,
  updated_at        TIMESTAMP(6)  NOT NULL,
  withdrawn_at      TIMESTAMP(6)  NULL,
  CONSTRAINT uk_users_email UNIQUE (email),
  CONSTRAINT uk_users_nickname UNIQUE (nickname)
);
COMMENT ON COLUMN users.password_hash IS '소셜 전용 계정은 NULL';
COMMENT ON COLUMN users.role IS 'USER|ADMIN';
COMMENT ON COLUMN users.status IS 'PENDING|ACTIVE|WITHDRAWN';
COMMENT ON COLUMN users.interest_reset_at IS '관심사 초기화 시각. 이후 반응만 점수에 반영 (탐색 초기화는 P2)';

CREATE TABLE social_accounts (
  id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT       NOT NULL,
  provider         VARCHAR(10)  NOT NULL,
  provider_user_id VARCHAR(100) NOT NULL,
  created_at       TIMESTAMP(6)  NOT NULL,
  CONSTRAINT uk_social UNIQUE (provider, provider_user_id),
  FOREIGN KEY (user_id) REFERENCES users (id)
);
COMMENT ON COLUMN social_accounts.provider IS 'GOOGLE (소셜 로그인은 Google만, P1)';

CREATE TABLE auth_tokens (
  id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT      NOT NULL,
  type       VARCHAR(20) NOT NULL,
  token_hash CHAR(64)    NOT NULL,
  expires_at TIMESTAMP(6) NOT NULL,
  used_at    TIMESTAMP(6) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_token_hash UNIQUE (token_hash),
  FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_token_user ON auth_tokens (user_id, type);
COMMENT ON COLUMN auth_tokens.type IS 'EMAIL_VERIFY(24h)|PASSWORD_RESET(30m)|REFRESH(14d)';
COMMENT ON COLUMN auth_tokens.token_hash IS 'SHA-256. 원문은 저장하지 않음';
COMMENT ON COLUMN auth_tokens.used_at IS '사용·폐기 시각';

CREATE TABLE regions (
  id      BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code    VARCHAR(10) NOT NULL,
  sido    VARCHAR(20) NOT NULL,
  sigungu VARCHAR(30) NOT NULL,
  CONSTRAINT uk_region_code UNIQUE (code)
);
CREATE INDEX idx_region_sido ON regions (sido);
COMMENT ON COLUMN regions.code IS '행정구역 코드(시·군·구)';

CREATE TABLE user_conditions (
  user_id        BIGINT      NOT NULL PRIMARY KEY,
  weekly_hours   SMALLINT     NULL,
  monthly_budget INT         NULL,
  place_pref     VARCHAR(10) NULL,
  social_pref    VARCHAR(10) NULL,
  region_id      BIGINT      NULL,
  updated_at     TIMESTAMP(6) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users (id),
  FOREIGN KEY (region_id) REFERENCES regions (id)
);
COMMENT ON COLUMN user_conditions.weekly_hours IS '활동 가능 시간(시간/주) 0~40. NULL=미입력';
COMMENT ON COLUMN user_conditions.monthly_budget IS '예산(원/월). NULL=미입력';
COMMENT ON COLUMN user_conditions.place_pref IS 'INDOOR|OUTDOOR|ANY';
COMMENT ON COLUMN user_conditions.social_pref IS 'ALONE|TOGETHER|ANY';
COMMENT ON COLUMN user_conditions.region_id IS '선호 지역';

