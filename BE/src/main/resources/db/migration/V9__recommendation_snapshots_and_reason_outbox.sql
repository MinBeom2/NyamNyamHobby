ALTER TABLE recommendation_items ADD COLUMN fallback_reason VARCHAR(200);
ALTER TABLE recommendation_items ADD COLUMN saved BOOLEAN NOT NULL DEFAULT FALSE;

-- 기존 추천은 원래 생성 시점의 값을 복원할 수 없으므로 마이그레이션 시점의 정보를 고정한다.
UPDATE recommendation_items i SET
  hobby_snapshot = jsonb_build_object('id',h.id,'name',h.name,'thumbnailUrl',h.thumbnail_url,'difficulty',h.difficulty,
    'sessionMinutes',jsonb_build_object('min',h.session_min_minutes,'max',h.session_max_minutes),
    'monthlyCost',jsonb_build_object('min',h.monthly_cost_min,'max',h.monthly_cost_max)),
  fallback_reason = h.name || ' 취미를 추천해요'
FROM hobbies h WHERE h.id = i.hobby_id;
UPDATE recommendation_items i SET saved = EXISTS (
  SELECT 1 FROM recommendations r JOIN user_hobbies uh ON uh.user_id=r.user_id
  WHERE r.id=i.recommendation_id AND uh.hobby_id=i.hobby_id);
UPDATE recommendations SET basis_text = '이전에 기록한 숏폼 반응을 바탕으로 추천했어요';

CREATE TABLE recommendation_reason_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recommendation_id BIGINT NOT NULL UNIQUE REFERENCES recommendations(id),
  payload JSONB NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_reason_outbox_pending ON recommendation_reason_outbox(next_attempt_at);
