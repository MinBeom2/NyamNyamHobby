COMMENT ON COLUMN hobbies.monthly_cost_min IS '월 지속 비용(원)';
COMMENT ON COLUMN hobbies.supplies IS '준비물';
COMMENT ON COLUMN hobbies.environment IS '활동 환경 설명';
COMMENT ON COLUMN hobbies.first_activity IS '초보자용 첫 활동';
