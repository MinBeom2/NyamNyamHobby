CREATE TABLE exploration_sessions (
  id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT      NULL,
  guest_key    CHAR(36)    NULL,
  status       VARCHAR(12) NOT NULL DEFAULT 'IN_PROGRESS',
  max_count    SMALLINT     NOT NULL DEFAULT 12,
  viewed_count SMALLINT     NOT NULL DEFAULT 0,
  started_at   TIMESTAMP(6) NOT NULL,
  ended_at     TIMESTAMP(6) NULL,
  FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_session_user ON exploration_sessions (user_id, started_at);
CREATE INDEX idx_session_guest ON exploration_sessions (guest_key);
COMMENT ON COLUMN exploration_sessions.guest_key IS '비회원 UUID. 이관 후 NULL (비회원 체험 P2, MVP는 항상 NULL)';
COMMENT ON COLUMN exploration_sessions.status IS 'IN_PROGRESS|COMPLETED|ABANDONED';

CREATE TABLE exploration_views (
  id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id  BIGINT      NOT NULL,
  short_id    BIGINT      NOT NULL,
  seq         SMALLINT     NOT NULL,
  play_failed BOOLEAN     NOT NULL DEFAULT FALSE,
  watched_seconds SMALLINT NOT NULL DEFAULT 0,
  watch_ratio DECIMAL(4,3) NULL,
  viewed_at   TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_view UNIQUE (session_id, short_id),
  FOREIGN KEY (session_id) REFERENCES exploration_sessions (id),
  FOREIGN KEY (short_id) REFERENCES shorts (id)
);
COMMENT ON COLUMN exploration_views.seq IS '세션 내 노출 순서 1~N (N = exploration.session-size, 기본안 12)';
COMMENT ON COLUMN exploration_views.watched_seconds IS '실제 재생 초(영상 길이 상한)';
COMMENT ON COLUMN exploration_views.watch_ratio IS 'watched_seconds ÷ duration_seconds (0~1)';

CREATE TABLE short_reactions (
  id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT      NULL,
  guest_key  CHAR(36)    NULL,
  short_id   BIGINT      NOT NULL,
  session_id BIGINT      NULL,
  type       VARCHAR(10) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_reaction_user UNIQUE (user_id, short_id),
  CONSTRAINT uk_reaction_guest UNIQUE (guest_key, short_id),
  FOREIGN KEY (user_id) REFERENCES users (id),
  FOREIGN KEY (short_id) REFERENCES shorts (id)
);
CREATE INDEX idx_reaction_type ON short_reactions (user_id, type, updated_at);
COMMENT ON COLUMN short_reactions.session_id IS '반응한 탐색 세션(보관함(P2)에서 반응 시 NULL)';
COMMENT ON COLUMN short_reactions.type IS 'LIKE|DISLIKE|IRRELEVANT';

