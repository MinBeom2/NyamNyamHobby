CREATE TABLE shorts (
  id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hobby_id          BIGINT       NULL,
  channel_id        BIGINT       NULL,
  youtube_video_id  VARCHAR(20)  NOT NULL,
